#!/usr/bin/env python3
"""Install the stdio bridge into the guest's default mount.

The bridge has exactly one source of truth: ``scripts/mcp/minis-mcp-stdio``.
Everything the app ships is generated from it, so the copy inside the guest can
never describe a different discovery order or a different endpoint file than the
one under test.

    python3 scripts/mcp/sync_stdio_to_assets.py           # regenerate
    python3 scripts/mcp/sync_stdio_to_assets.py --check    # CI: fail on drift

Generated files
---------------
* ``<default_mount>/usr/local/lib/minis/mcp/minis_mcp_stdio.py`` — the bridge
  itself, byte-identical to the source.
* ``<default_mount>/usr/local/bin/minis-mcp-stdio`` — POSIX sh wrapper that
  makes sure python3 exists before exec'ing the bridge (first boot on a fresh
  rootfs has no interpreter until the dev setup runs).
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "scripts" / "mcp" / "minis-mcp-stdio"
MOUNT = REPO / "src/android/app/src/main/assets/default_mount"
INSTALLED = MOUNT / "usr/local/lib/minis/mcp/minis_mcp_stdio.py"
WRAPPER = MOUNT / "usr/local/bin/minis-mcp-stdio"

WRAPPER_BODY = """#!/bin/sh
# minis-mcp-stdio — speak MCP over stdio, run on Minis Ultra's HTTP MCP server.
#
# Generated by scripts/mcp/sync_stdio_to_assets.py from
# scripts/mcp/minis-mcp-stdio — edit the source, not this file.
#
# Why the wrapper: a client spawns this binary as a child process, and a MCP
# client that gets "python3: not found" reports a broken server with no hint.
# The first shell on a fresh rootfs can run before the dev setup installed an
# interpreter, so make the dependency explicit here instead of failing in the
# client's logs.
set -e
LOG="/var/minis/shared/mcp/stdio-bridge.log"
if ! command -v python3 > /dev/null 2>&1; then
  hash -r 2>/dev/null
  if ! command -v python3 > /dev/null 2>&1; then
    mkdir -p /var/minis/shared/mcp 2>/dev/null || true
    if command -v apt-get > /dev/null 2>&1; then
      DEBIAN_FRONTEND=noninteractive apt-get install -y python3 >> "$LOG" 2>&1 || true
    fi
  fi
fi
exec python3 /usr/local/lib/minis/mcp/minis_mcp_stdio.py "$@"
"""


def target_body() -> str:
    return SOURCE.read_text(encoding="utf-8")


def main(argv: list[str]) -> int:
    check = "--check" in argv
    if not SOURCE.is_file():
        print(f"missing bridge source: {SOURCE}", file=sys.stderr)
        return 2
    body = target_body()

    drift: list[str] = []
    for path, expected in ((INSTALLED, body), (WRAPPER, WRAPPER_BODY)):
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != expected:
            drift.append(str(path.relative_to(REPO)))

    if check:
        if drift:
            print("stdio bridge assets are stale:", file=sys.stderr)
            for name in drift:
                print(f"  {name}", file=sys.stderr)
            print("run: python3 scripts/mcp/sync_stdio_to_assets.py", file=sys.stderr)
            return 1
        print("stdio bridge assets match scripts/mcp/minis-mcp-stdio")
        return 0

    INSTALLED.parent.mkdir(parents=True, exist_ok=True)
    INSTALLED.write_text(body, encoding="utf-8")
    INSTALLED.chmod(0o755)
    WRAPPER.parent.mkdir(parents=True, exist_ok=True)
    WRAPPER.write_text(WRAPPER_BODY, encoding="utf-8")
    WRAPPER.chmod(0o755)
    for name in drift:
        print(f"updated {name}")
    if not drift:
        print("already in sync")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
