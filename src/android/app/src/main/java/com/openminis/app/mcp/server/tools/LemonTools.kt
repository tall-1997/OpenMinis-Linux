package com.openminis.app.mcp.server.tools

import android.util.Log
import com.openminis.app.mcp.server.McpServerCore
import org.json.JSONArray
import org.json.JSONObject

/**
 * [T-lemon-integration] The on-device tool catalog from lemon-kernel-opensource,
 * embedded as two MCP tools instead of 358 separate specs.
 *
 * Why two and not 358: every MCP client pays `tools/list` size on every
 * session (`list_tools` is the first thing an agent calls), and 358 entries
 * with Chinese descriptions would dominate the prompt of any client that
 * inlines the list. One catalog tool + one call tool keeps the surface at
 * two entries while the whole catalog stays reachable — the same shape the
 * upstream panel used, minus the second process.
 *
 * Execution goes through the app's OWN gate ([McpToolShared.gateAndRun]):
 * `SecurityGate.classify` → `decide` → `audit`, driven by the session's
 * [com.openminis.app.security.PermissionMode]. That is the whole point of
 * moving the panel in-app: the Python panel needed its own copy of the
 * three-tier model, and the two could disagree. Here there is one gate.
 *
 * Catalog source: `assets/lemon/catalog.json`, generated by
 * `scripts/lemon/gen_catalog.py` from the upstream plugin shells plus the
 * externalized `groups.json` / `risk.json`. Regenerate rather than hand-edit.
 *
 * No `delegated` branch here, unlike the standalone panel: its "hand settings
 * edits to the settings screen, deletions to the session menu" rule assumed a
 * human clicking a UI next to the agent. Inside the app only the agent calls
 * these tools, so there is nobody to hand the action to — routing
 * `settings put` back at a screen would be a dead end, not a safeguard.
 * The three tiers themselves live in [com.openminis.app.security.SecurityGate].
 */
internal object LemonCatalog {

    private const val TAG = "LemonCatalog"
    private const val ASSET = "lemon/catalog.json"

    /**
     * Numeric rank of a domain tag (`D6-kernel` → 6), so `D10` sorts after
     * `D8` instead of lexically before it. The label half is never parsed —
     * it comes from the asset and may be any language.
     */
    private fun domainRank(tag: String): Int {
        var i = 0
        while (i < tag.length && !tag[i].isDigit()) i++
        var n = 0
        while (i < tag.length && tag[i].isDigit()) {
            n = n * 10 + (tag[i] - '0')
            i++
        }
        return if (n == 0) Int.MAX_VALUE else n
    }

    internal data class Tool(
        val name: String,
        val desc: String,
        val cmd: String,
        val params: String,
        val required: String,
        val timeoutMs: Int,
        val domain: String,
        val risk: String,
        val readOnly: Boolean,
    ) {
        fun toJson(): JSONObject = JSONObject().apply {
            put("name", name)
            put("desc", desc)
            put("domain", domain)
            put("risk", risk)
            put("ro", readOnly)
        }
    }

    @Volatile
    private var cache: Map<String, Tool>? = null

    /** Loads once per process; an unreadable asset yields an empty catalog, never a crash. */
    fun all(context: android.content.Context?): Map<String, Tool> {
        cache?.let { return it }
        synchronized(this) {
            cache?.let { return it }
            val loaded = runCatching {
                val raw = context?.assets?.open(ASSET)?.bufferedReader()?.use { it.readText() }
                    ?: return@runCatching emptyMap()
                val arr = JSONObject(raw).optJSONArray("tools") ?: JSONArray()
                buildMap {
                    for (i in 0 until arr.length()) {
                        val o = arr.optJSONObject(i) ?: continue
                        val name = o.optString("name", "")
                        if (name.isEmpty()) continue
                        put(
                            name,
                            Tool(
                                name = name,
                                desc = o.optString("desc", ""),
                                cmd = o.optString("cmd", ""),
                                params = o.optString("params", ""),
                                required = o.optString("required", ""),
                                timeoutMs = o.optInt("timeoutMs", 15000).coerceIn(1000, 120_000),
                                domain = o.optString("domain", "D9"),
                                risk = o.optString("risk", "medium"),
                                readOnly = o.optBoolean("ro", false),
                            ),
                        )
                    }
                }
            }.getOrElse {
                Log.w(TAG, "catalog unreadable: ${it.message}")
                emptyMap()
            }
            cache = loaded
            return loaded
        }
    }

    /** Domain counts in display order, for the panel and the list tool. */
    fun domainCounts(tools: Collection<Tool>): JSONArray = JSONArray().apply {
        tools.groupingBy { it.domain }.eachCount()
            .toList()
            .sortedBy { (domain, _) -> domainRank(domain) }
            .forEach { (d, n) -> put(JSONObject().put("domain", d).put("count", n)) }
    }
}

/**
 * Two tools: `lemon_list` (search the catalog) and `lemon_call` (run one).
 *
 * `lemon_call` takes a `_reason` argument: the app gate already decides
 * whether a confirmation is needed, and when it says "needs confirm" the
 * reason is what the audit trail records. That keeps MCP's no-popup
 * constraint honest without inventing a second permission model.
 */
internal fun lemonTools(deps: McpToolDeps): List<McpToolSpec> = listOf(
    McpToolSpec(
        name = "lemon_list",
        description = "List the on-device tool catalog (lemon kernel: system, file, app, " +
            "network, kernel, debug, reverse, orchestration). Filter by domain, keyword or risk. " +
            "Returns name, domain, risk and one-line description; call lemon_call to execute.",
        schema = JSONObject().apply {
            put("type", "object")
            put("properties", JSONObject().apply {
                put("domain", JSONObject().apply {
                    put("type", "string")
                    put("description", "Domain filter, e.g. D6. Empty = all.")
                })
                put("keyword", JSONObject().apply {
                    put("type", "string")
                    put("description", "Substring match on name or description.")
                })
                put("risk", JSONObject().apply {
                    put("type", "string")
                    put("description", "low | medium | high")
                })
                put("limit", JSONObject().apply {
                    put("type", "integer")
                    put("description", "Max entries (default 60, cap 200).")
                })
            })
        },
        handler = { lemonList(deps, it) },
    ),
    McpToolSpec(
        name = "lemon_call",
        description = "Run one tool from the lemon catalog by name. Arguments are passed as " +
            "shell-escaped key=value pairs. When the session gate requires confirmation, " +
            "pass _reason to state why — it is recorded in the audit trail.",
        schema = JSONObject().apply {
            put("type", "object")
            put("properties", JSONObject().apply {
                put("name", JSONObject().apply {
                    put("type", "string")
                    put("description", "Tool name from lemon_list.")
                })
                put("args", JSONObject().apply {
                    put("type", "object")
                    put("description", "Parameter values; keys come from the tool's params list.")
                })
                put("_reason", JSONObject().apply {
                    put("type", "string")
                    put("description", "Why this run is needed; recorded when a confirmation is required.")
                })
            })
            put("required", JSONArray().put("name"))
        },
        handler = { lemonCall(deps, it) },
    ),
)

private fun lemonList(deps: McpToolDeps, arguments: JSONObject): McpServerCore.CallResult {
    val catalog = LemonCatalog.all(deps.context)
    if (catalog.isEmpty()) {
        return McpToolShared.error("Error: lemon catalog asset missing or unreadable")
    }
    val domain = arguments.optString("domain", "").trim()
    val keyword = arguments.optString("keyword", "").trim().lowercase()
    val risk = arguments.optString("risk", "").trim().lowercase()
    val limit = arguments.optInt("limit", 60).coerceIn(1, 200)

    val hits = catalog.values.asSequence()
        .filter { domain.isEmpty() || it.domain == domain }
        .filter { risk.isEmpty() || it.risk == risk }
        .filter {
            keyword.isEmpty() ||
                it.name.lowercase().contains(keyword) ||
                it.desc.lowercase().contains(keyword)
        }
        .sortedBy { it.name }
        .toList()

    val body = JSONObject().apply {
        put("total", catalog.size)
        put("matched", hits.size)
        put("domains", LemonCatalog.domainCounts(catalog.values))
        put("tools", JSONArray().apply { hits.take(limit).forEach { put(it.toJson()) } })
    }
    return McpServerCore.CallResult(JSONArray().put(McpToolShared.text(body.toString(2))))
}

private fun lemonCall(deps: McpToolDeps, arguments: JSONObject): McpServerCore.CallResult {
    val name = arguments.optString("name", "").trim()
    if (name.isEmpty()) return McpToolShared.error("Error: 'name' is required")

    val tool = LemonCatalog.all(deps.context)[name]
        ?: return McpToolShared.error(
            "Error: unknown lemon tool '$name'. Call lemon_list first.",
        )
    if (tool.cmd.isBlank()) {
        return McpToolShared.error("Error: '$name' has no command body in the catalog")
    }

    val argv = arguments.optJSONObject("args") ?: JSONObject()
    val reason = arguments.optString("_reason", "").trim()
    val command = try {
        buildCommand(tool, argv)
    } catch (e: IllegalArgumentException) {
        return McpToolShared.error("Error: ${e.message}")
    }
    val timeoutSec = (tool.timeoutMs / 1000).coerceIn(2, 120)

    // The gate classifies by name + args; passing the rendered command gives it
    // the same evidence the shell tool would see. `_reason` is not part of the
    // command, so it is stripped before rendering (see buildCommand).
    return McpToolShared.gateAndRun(deps, "lemon_$name", command) {
        val result = McpToolShared.runInGuest(command, timeoutSec)
        val out = JSONObject().apply {
            put("tool", name)
            put("domain", tool.domain)
            put("risk", tool.risk)
            put("exit_code", result.exitCode)
            put("output", result.output)
            put("duration_ms", result.durationMs)
            put("timed_out", result.timedOut)
            if (reason.isNotEmpty()) put("reason", reason)
        }
        McpServerCore.CallResult(
            JSONArray().put(McpToolShared.text(out.toString(2))),
            isError = result.exitCode != 0,
        )
    }
}

/**
 * Render `cmd` with `$key` substituted from [argv].
 *
 * Values are shell-escaped ([McpToolShared.shellEscape]) — the upstream panel
 * did plain `str.format`, so a value containing `;` or `$(...)` was code
 * execution. Missing required parameters fail loudly instead of silently
 * expanding to an empty string.
 */
private fun buildCommand(tool: LemonCatalog.Tool, argv: JSONObject): String {
    val required = tool.required.split('|').map { it.trim() }.filter { it.isNotEmpty() }
    val missing = required.filter { argv.optString(it, "").isEmpty() }
    if (missing.isNotEmpty()) {
        throw IllegalArgumentException("missing required: ${missing.joinToString(", ")}")
    }
    var out = tool.cmd
    val keys = argv.keys()
    while (keys.hasNext()) {
        val k = keys.next()
        if (k == "_reason") continue
        val v = argv.optString(k, "")
        out = out.replace("${'$'}$k", McpToolShared.shellEscape(v))
    }
    return out
}
