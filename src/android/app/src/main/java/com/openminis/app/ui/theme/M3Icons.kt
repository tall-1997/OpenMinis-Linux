/**
 * [T-two-styles] 双向图标变体归一化器：按当前视觉系统把 material-icons 的
 * Filled/Outlined 变体归一。
 *
 * 动态取色（M3 Expressive）→ Outlined（Material Symbols 风格）
 * 非动态（Apple）→ Filled/Default（SF Symbols 风格）
 *
 * 之所以是双向归一化而不是单向映射：调用点历史上两种喂法并存——chat 系传
 * Filled，settings 系传 Outlined（开源初始提交即如此）。单向表对其中一半必然
 * 查不到键、原样返回，于是开关拨了图标也没变化（PR #126 的回归根源）。双向表
 * 让任何喂法都得到当前模式的正确变体，且幂等：已归一过的输入再次经过不会变。
 *
 * 注册表（iconPairs）之外的图标原样返回，不崩溃、不切换。给设置页新增图标时，
 * 把 (Filled, Outlined) 对加进 iconPairs；ui/settings 下引用到的每个图标都应
 * 有对应条目（M3IconsTest 抽样把关）。
