/** 动态模式查表：Filled → Outlined。 */
private val filledToOutlined: Map<ImageVector, ImageVector> = iconPairs.toMap()

/** 非动态模式查表：Outlined → Filled。 */
private val outlinedToFilled: Map<ImageVector, ImageVector> =
    iconPairs.associate { it.second to it.first }

/**
 * 归一化入口（非 Composable 版）。dynamicActive = 当前是否处于动态取色模式。
 * 两个方向都查不到键的图标原样返回。
 */
fun m3Icon(icon: ImageVector, dynamicActive: Boolean): ImageVector {
    if (dynamicActive) return filledToOutlined[icon] ?: icon
    return outlinedToFilled[icon] ?: icon
}

/** Composable 便捷版：自动读 LocalUseRoundedIcons（跟随动态取色开关）。 */
@Composable
@ReadOnlyComposable
fun m3Icon(icon: ImageVector): ImageVector = m3Icon(icon, LocalUseRoundedIcons.current)
